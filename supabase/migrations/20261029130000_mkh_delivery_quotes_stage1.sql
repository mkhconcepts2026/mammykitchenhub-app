-- MKH Stage 1: trusted delivery quote and distance rate-card foundation.
-- Additive only: does not alter orders, order-creation RPCs, wallets, ledgers, payout functions,
-- settlement functions, existing orders, or historic financial records.
-- Apply to the MKH TEST Supabase project only after reviewing this migration.

BEGIN;

CREATE TABLE IF NOT EXISTS public.delivery_distance_rate_cards (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rate_version integer NOT NULL,
    min_distance_km numeric(7,3) NOT NULL,
    max_distance_km numeric(7,3) NOT NULL,
    customer_delivery_fee numeric(12,2) NOT NULL,
    rider_payout numeric(12,2) NOT NULL,
    active boolean NOT NULL DEFAULT true,
    effective_from timestamptz NOT NULL DEFAULT now(),
    effective_to timestamptz NULL,
    CONSTRAINT delivery_distance_rate_cards_distance_ck
      CHECK (min_distance_km >= 0 AND max_distance_km > min_distance_km),
    CONSTRAINT delivery_distance_rate_cards_amounts_ck
      CHECK (customer_delivery_fee >= 1500 AND rider_payout >= 0),
    CONSTRAINT delivery_distance_rate_cards_dates_ck
      CHECK (effective_to IS NULL OR effective_to > effective_from),
    CONSTRAINT delivery_distance_rate_cards_version_band_uq
      UNIQUE (rate_version, min_distance_km, max_distance_km)
);

CREATE INDEX IF NOT EXISTS delivery_distance_rate_cards_lookup_idx
  ON public.delivery_distance_rate_cards
    (active, rate_version, min_distance_km, max_distance_km, effective_from, effective_to);

-- Version 1 follows the recorded MKH working distance schedule. The pilot quote API
-- currently enforces the recorded 3 km maximum road route. Rider payout is stored
-- as reference data only here; this migration does not wire or change payouts.
INSERT INTO public.delivery_distance_rate_cards
  (rate_version, min_distance_km, max_distance_km, customer_delivery_fee, rider_payout, active)
SELECT 1, x.min_km, x.max_km, x.delivery_fee, x.rider_payout, true
FROM (VALUES
  (0.000::numeric, 1.000::numeric, 1500::numeric,  800::numeric),
  (1.000::numeric, 2.000::numeric, 1700::numeric,  900::numeric),
  (2.000::numeric, 3.000::numeric, 1900::numeric, 1000::numeric),
  (3.000::numeric, 4.000::numeric, 2100::numeric, 1200::numeric),
  (4.000::numeric, 5.000::numeric, 2300::numeric, 1400::numeric),
  (5.000::numeric, 6.000::numeric, 2500::numeric, 1600::numeric),
  (6.000::numeric, 7.000::numeric, 2700::numeric, 1800::numeric),
  (7.000::numeric, 8.000::numeric, 2900::numeric, 2000::numeric),
  (8.000::numeric, 9.000::numeric, 3100::numeric, 2200::numeric),
  (9.000::numeric,10.000::numeric, 3300::numeric, 2400::numeric)
) AS x(min_km, max_km, delivery_fee, rider_payout)
WHERE NOT EXISTS (
  SELECT 1 FROM public.delivery_distance_rate_cards r
  WHERE r.rate_version = 1
    AND r.min_distance_km = x.min_km
    AND r.max_distance_km = x.max_km
);

CREATE TABLE IF NOT EXISTS public.delivery_quotes (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    customer_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE RESTRICT,
    vendor_id uuid NOT NULL REFERENCES public.vendors(id) ON DELETE RESTRICT,
    cart_hash text NOT NULL CHECK (length(cart_hash) = 64),
    destination_address_hash text NOT NULL CHECK (length(destination_address_hash) = 64),
    subtotal_amount numeric(12,2) NOT NULL CHECK (subtotal_amount > 0),
    route_distance_meters integer NOT NULL CHECK (route_distance_meters > 0),
    route_distance_km numeric(7,3) NOT NULL CHECK (route_distance_km > 0 AND route_distance_km <= 10),
    rate_version integer NOT NULL,
    customer_delivery_fee numeric(12,2) NOT NULL CHECK (customer_delivery_fee >= 1500),
    platform_fee numeric(12,2) NOT NULL DEFAULT 300 CHECK (platform_fee >= 0),
    status text NOT NULL DEFAULT 'quoted'
      CHECK (status IN ('quoted', 'consumed', 'expired', 'superseded', 'rejected')),
    created_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL,
    consumed_at timestamptz NULL,
    CONSTRAINT delivery_quotes_expiry_ck CHECK (expires_at > created_at),
    CONSTRAINT delivery_quotes_consumed_ck CHECK ((status = 'consumed') = (consumed_at IS NOT NULL))
);

CREATE INDEX IF NOT EXISTS delivery_quotes_customer_recent_idx
  ON public.delivery_quotes(customer_id, created_at DESC);
CREATE INDEX IF NOT EXISTS delivery_quotes_expiry_idx
  ON public.delivery_quotes(status, expires_at);

ALTER TABLE public.delivery_distance_rate_cards ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.delivery_quotes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.delivery_distance_rate_cards FROM anon, authenticated;
REVOKE ALL ON public.delivery_quotes FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.delivery_distance_rate_cards TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.delivery_quotes TO service_role;

COMMIT;

